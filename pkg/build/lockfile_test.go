package build

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/google/go-cmp/cmp"
)

func testLockfile() *BaseImageLockfile {
	return &BaseImageLockfile{
		Version: BaseImageLockfileVersion,
		DefaultBaseImage: LockedBaseImage{
			Ref:    "cgr.dev/chainguard/static:latest",
			Pinned: "cgr.dev/chainguard/static@sha256:aaaa",
		},
		BaseImageOverrides: map[string]LockedBaseImage{
			"github.com/google/ko": {
				Ref:    "golang:latest",
				Pinned: "golang@sha256:bbbb",
			},
		},
	}
}

func TestLockfileRoundTrip(t *testing.T) {
	path := filepath.Join(t.TempDir(), "ko.lock")
	want := testLockfile()
	if err := want.Save(path); err != nil {
		t.Fatalf("Save() = %v", err)
	}

	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("ReadFile() = %v", err)
	}
	if !strings.HasPrefix(string(b), "# This file is generated by `ko lock`.") {
		t.Errorf("lockfile missing generated header, got:\n%s", b)
	}

	got, err := LoadBaseImageLockfile(path)
	if err != nil {
		t.Fatalf("LoadBaseImageLockfile() = %v", err)
	}
	if diff := cmp.Diff(want, got); diff != "" {
		t.Errorf("round trip mismatch (-want,+got):\n%s", diff)
	}

	// Saving again must be byte-for-byte stable.
	if err := got.Save(path); err != nil {
		t.Fatalf("Save() = %v", err)
	}
	b2, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("ReadFile() = %v", err)
	}
	if !bytes.Equal(b, b2) {
		t.Errorf("lockfile not stable across saves:\n%s\n---\n%s", b, b2)
	}
}

func TestLoadBaseImageLockfileErrors(t *testing.T) {
	if _, err := LoadBaseImageLockfile(filepath.Join(t.TempDir(), "missing.lock")); err == nil {
		t.Error("LoadBaseImageLockfile() on missing file did not error")
	}

	path := filepath.Join(t.TempDir(), "ko.lock")
	if err := os.WriteFile(path, []byte("version: 999\n"), 0644); err != nil {
		t.Fatal(err)
	}
	if _, err := LoadBaseImageLockfile(path); err == nil {
		t.Error("LoadBaseImageLockfile() with unsupported version did not error")
	}
}

func TestLockfileVerify(t *testing.T) {
	lock := testLockfile()

	t.Run("no drift", func(t *testing.T) {
		if drift := lock.Verify(testLockfile()); len(drift) != 0 {
			t.Errorf("Verify() = %v, want no drift", drift)
		}
	})

	t.Run("digest moved", func(t *testing.T) {
		current := testLockfile()
		current.DefaultBaseImage.Pinned = "cgr.dev/chainguard/static@sha256:cccc"
		drift := lock.Verify(current)
		if len(drift) != 1 || !strings.Contains(drift[0], "moved") {
			t.Errorf("Verify() = %v, want one 'moved' drift", drift)
		}
	})

	t.Run("configured ref changed", func(t *testing.T) {
		current := testLockfile()
		current.DefaultBaseImage.Ref = "cgr.dev/chainguard/static:latest-glibc"
		drift := lock.Verify(current)
		if len(drift) == 0 || !strings.Contains(drift[0], "changed") {
			t.Errorf("Verify() = %v, want a 'changed' drift", drift)
		}
	})

	t.Run("override added and removed", func(t *testing.T) {
		current := testLockfile()
		delete(current.BaseImageOverrides, "github.com/google/ko")
		current.BaseImageOverrides["github.com/google/ko/test"] = LockedBaseImage{
			Ref:    "golang:1.24",
			Pinned: "golang@sha256:dddd",
		}
		drift := lock.Verify(current)
		if len(drift) != 2 {
			t.Errorf("Verify() = %v, want 2 drift entries", drift)
		}
	})
}
