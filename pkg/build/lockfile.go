package build

import (
	"bytes"
	"fmt"
	"os"
	"sort"

	"go.yaml.in/yaml/v4"
)

// BaseImageLockfileVersion is the current version of the base image
// lockfile format written by `ko lock`.
const BaseImageLockfileVersion = 1

// DefaultLockfile is the default name of the base image lockfile.
const DefaultLockfile = "ko.lock"

// lockfileHeader is prepended to generated lockfiles.
const lockfileHeader = "# This file is generated by `ko lock`. Do not edit by hand; run `ko lock` to refresh it.\n"

// LockedBaseImage records a single base image reference pinned to an
// immutable digest.
type LockedBaseImage struct {
	// Ref is the base image reference as configured (e.g. in .ko.yaml),
	// typically a mutable tag such as cgr.dev/chainguard/static:latest.
	Ref string `yaml:"ref"`

	// Pinned is the same reference resolved to an immutable digest, e.g.
	// cgr.dev/chainguard/static@sha256:deadbeef...
	Pinned string `yaml:"pinned"`
}

// BaseImageLockfile is the on-disk format of the base image lockfile
// (ko.lock). Its structure mirrors the base image configuration keys of
// .ko.yaml.
type BaseImageLockfile struct {
	// Version is the lockfile format version.
	Version int `yaml:"version"`

	// DefaultBaseImage pins the configured defaultBaseImage.
	DefaultBaseImage LockedBaseImage `yaml:"defaultBaseImage"`

	// BaseImageOverrides pins the configured baseImageOverrides, keyed by
	// import path.
	BaseImageOverrides map[string]LockedBaseImage `yaml:"baseImageOverrides,omitempty"`
}

// LoadBaseImageLockfile reads and parses a base image lockfile.
func LoadBaseImageLockfile(path string) (*BaseImageLockfile, error) {
	b, err := os.ReadFile(path) //nolint:gosec // The lockfile path is intentionally user-controlled.
	if err != nil {
		return nil, err
	}
	var lock BaseImageLockfile
	if err := yaml.Unmarshal(b, &lock); err != nil {
		return nil, fmt.Errorf("parsing %s: %w", path, err)
	}
	if lock.Version != BaseImageLockfileVersion {
		return nil, fmt.Errorf("%s: unsupported lockfile version %d (expected %d)", path, lock.Version, BaseImageLockfileVersion)
	}
	return &lock, nil
}

// Save writes the lockfile to path in a deterministic form.
func (l *BaseImageLockfile) Save(path string) error {
	var buf bytes.Buffer
	buf.WriteString(lockfileHeader)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(l); err != nil {
		return fmt.Errorf("encoding lockfile: %w", err)
	}
	if err := enc.Close(); err != nil {
		return fmt.Errorf("encoding lockfile: %w", err)
	}
	return os.WriteFile(path, buf.Bytes(), 0644) //nolint:gosec // Lockfiles are meant to be committed and shared.
}

// Verify compares the lockfile against current, a lockfile built from the
// currently configured base image references resolved to their current
// digests. It returns a list of human-readable drift descriptions; an empty
// result means the lockfile is up to date.
func (l *BaseImageLockfile) Verify(current *BaseImageLockfile) []string {
	var drift []string
	drift = append(drift, verifyLocked("defaultBaseImage", l.DefaultBaseImage, current.DefaultBaseImage)...)

	keys := map[string]struct{}{}
	for k := range l.BaseImageOverrides {
		keys[k] = struct{}{}
	}
	for k := range current.BaseImageOverrides {
		keys[k] = struct{}{}
	}
	sorted := make([]string, 0, len(keys))
	for k := range keys {
		sorted = append(sorted, k)
	}
	sort.Strings(sorted)
	for _, k := range sorted {
		name := fmt.Sprintf("baseImageOverrides[%s]", k)
		locked, lok := l.BaseImageOverrides[k]
		cur, cok := current.BaseImageOverrides[k]
		switch {
		case !lok:
			drift = append(drift, fmt.Sprintf("%s: no locked entry for configured base image %q; run `ko lock`", name, cur.Ref))
		case !cok:
			drift = append(drift, fmt.Sprintf("%s: locked entry for %q is no longer configured; run `ko lock`", name, locked.Ref))
		default:
			drift = append(drift, verifyLocked(name, locked, cur)...)
		}
	}
	return drift
}

func verifyLocked(name string, locked, current LockedBaseImage) []string {
	var drift []string
	if locked.Ref != current.Ref {
		drift = append(drift, fmt.Sprintf("%s: configured base image changed from %q (locked) to %q (current); run `ko lock`", name, locked.Ref, current.Ref))
	}
	if locked.Pinned != current.Pinned {
		drift = append(drift, fmt.Sprintf("%s: base image %q moved: locked %s, currently resolves to %s; run `ko lock`", name, current.Ref, locked.Pinned, current.Pinned))
	}
	return drift
}
