// lockFileHeader is prepended to generated lock files.
const lockFileHeader = `# Auto-generated by "ko lock". Do not edit by hand.
# Pins base image references to digests for reproducible builds.
# Regenerate with "ko lock"; check freshness with "ko lock --verify".
`

// lockFile mirrors the base image related fields of `.ko.yaml`, with every
// reference pinned to a digest.
type lockFile struct {
	DefaultBaseImage   string            `yaml:"defaultBaseImage,omitempty"`
	BaseImageOverrides map[string]string `yaml:"baseImageOverrides,omitempty"`
}

// readLockFile parses the lock file at path.
func readLockFile(path string) (*lockFile, error) {
	/* #nosec G304 -- the lock file path is intentionally user-controlled. */
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	lf := &lockFile{}
	if err := yaml.Unmarshal(b, lf); err != nil {
		return nil, fmt.Errorf("parsing lock file %s: %w", path, err)
	}
	return lf, nil
}

// write serializes the lock file to path in a deterministic form.
func (lf *lockFile) write(path string) error {
	b, err := yaml.Marshal(lf)
	if err != nil {
		return err
	}
	/* #nosec G306 -- the lock file is meant to be committed and shared. */
	return os.WriteFile(path, append([]byte(lockFileHeader), b...), 0o644)
}

// entries returns the locked references keyed like BuildOptions: the empty
// string key holds the default base image, other keys are (lowercase)
// import paths.
func (lf *lockFile) entries() map[string]string {
	m := map[string]string{}
	if lf.DefaultBaseImage != "" {
		m[""] = lf.DefaultBaseImage
	}
	maps.Copy(m, lf.BaseImageOverrides)
	return m
}

// applyToBuildOptions rewrites the base image configuration in bo to the
// digest-pinned references recorded in the lock file.
func (lf *lockFile) applyToBuildOptions(bo *options.BuildOptions) {
	if lf.DefaultBaseImage != "" {
		bo.BaseImage = lf.DefaultBaseImage
	}
	for k, v := range lf.BaseImageOverrides {
		bo.BaseImageOverrides[strings.ToLower(k)] = v
	}
}

// lockFileFor resolves every base image referenced by bo to a digest-pinned
// reference using resolve, and returns the resulting lock file.
func lockFileFor(bo *options.BuildOptions, resolve func(ref string) (string, error)) (*lockFile, error) {
	lf := &lockFile{BaseImageOverrides: map[string]string{}}

	if bo.BaseImage != "" {
		pinned, err := resolve(bo.BaseImage)
		if err != nil {
			return nil, fmt.Errorf("resolving defaultBaseImage %q: %w", bo.BaseImage, err)
		}
		lf.DefaultBaseImage = pinned
	}

	// Sort keys so resolution errors are deterministic.
	for _, k := range slices.Sorted(maps.Keys(bo.BaseImageOverrides)) {
		pinned, err := resolve(bo.BaseImageOverrides[k])
		if err != nil {
			return nil, fmt.Errorf("resolving baseImageOverrides[%q] %q: %w", k, bo.BaseImageOverrides[k], err)
		}
		lf.BaseImageOverrides[k] = pinned
	}
	if len(lf.BaseImageOverrides) == 0 {
		lf.BaseImageOverrides = nil
	}
	return lf, nil
}

// diffLock compares the locked references against the currently resolved
// ones and returns a human-readable list of differences. An empty result
// means the lock file is up to date.
func diffLock(locked, current *lockFile) []string {
	le, ce := locked.entries(), current.entries()
	var diffs []string
	for _, k := range slices.Sorted(maps.Keys(le)) {
		want := le[k]
		got, ok := ce[k]
		name := lockEntryName(k)
		if !ok {
			diffs = append(diffs, fmt.Sprintf("%s: locked as %s, but no longer configured", name, want))
		} else if got != want {
			diffs = append(diffs, fmt.Sprintf("%s: locked as %s, but currently resolves to %s", name, want, got))
		}
	}
	for _, k := range slices.Sorted(maps.Keys(ce)) {
		if _, ok := le[k]; !ok {
			diffs = append(diffs, fmt.Sprintf("%s: resolves to %s, but is not in the lock file", lockEntryName(k), ce[k]))
		}
	}
	return diffs
}

func lockEntryName(key string) string {
	if key == "" {
		return "defaultBaseImage"
	}
	return fmt.Sprintf("baseImageOverrides[%q]", key)
}

// lockFilePath returns the lock file path, resolved relative to the build
// working directory when it is not absolute.
func lockFilePath(bo *options.BuildOptions) string {
	if filepath.IsAbs(bo.LockFile) {
		return bo.LockFile
	}
	return filepath.Join(bo.WorkingDirectory, bo.LockFile)
}

// applyLockFileToBuildOptions loads the lock file and pins bo's base images
// to the locked digests. A missing lock file is not an error; it only means
// base images are not pinned.
func applyLockFileToBuildOptions(bo *options.BuildOptions, path string) error {
	lf, err := readLockFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	lf.applyToBuildOptions(bo)
	return nil
}

// parseLockedReference validates that a locked reference is digest-pinned.
func parseLockedReference(ref string) error {
	if _, err := name.NewDigest(ref); err != nil {
		return fmt.Errorf("locked base image %q is not a digest-pinned reference: %w", ref, err)
	}
	return nil
}
